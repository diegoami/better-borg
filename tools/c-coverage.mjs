#!/usr/bin/env node
/**
 * The C-function coverage map (#34): every `borg_*` function the 4.2.6 C
 * borg defines, and whether the port names it anywhere - by its C name
 * (the port cites C names in comments, e.g. "borg_flow_recover
 * (borg-flow-misc.c)"), by its camelCase twin (`borgFlowRecover`), or by
 * a shorter camelCase suffix (`auxBless` for borg_defend_aux_bless).
 *
 *   node tools/c-coverage.mjs                 summary on stdout
 *   node tools/c-coverage.mjs --write         also write docs/audit/c-coverage.md
 *
 * An uncovered function is a CANDIDATE gap, not a verdict: it may be
 * C-only plumbing (keypress queues, screen scraping, the cheat pipe) with
 * nothing to port, or merged into another function under a different name.
 * Each uncovered one is classified by reading it (docs/audit/), the way the
 * declared-gaps inventory classifies the port's own markers. A covered one
 * is named, not proven faithful: the subsystem audit checks those.
 *
 * Reads the C from ../neo-angband/reference/src/borg/ and the port's src/
 * (tests excluded).
 */

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(fileURLToPath(new URL("./", import.meta.url)), "..");
const C_DIR = resolve(ROOT, "..", "neo-angband", "reference", "src", "borg");
const SRC = join(ROOT, "src");

/** Every borg_* function DEFINED in a C file: a line starting with a type that names it before "(". */
function definitions(file) {
  const out = [];
  const lines = readFileSync(join(C_DIR, file), "utf8").split("\n");
  lines.forEach((line, i) => {
    const m = /^[a-z][^=;(]*?[\s*](borg_[a-z0-9_]+)\(/u.exec(line);
    if (m === null || /^\s/u.test(line)) return;
    /* A prototype ends in ");" on its own line; a definition does not. */
    if (/\)\s*;\s*$/u.test(line)) return;
    out.push({ name: m[1], line: i + 1 });
  });
  return out;
}

function camel(name) {
  return name.replace(/_([a-z0-9])/gu, (_, c) => c.toUpperCase());
}

function walk(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((d) =>
    d.isDirectory() ? walk(join(dir, d.name)) : d.name.endsWith(".ts") && !d.name.endsWith(".test.ts") ? [join(dir, d.name)] : [],
  );
}

const port = walk(SRC).map((path) => ({ path: path.slice(ROOT.length + 1), text: readFileSync(path, "utf8") }));

/**
 * The names the port may use for a C function: the C name, its camelCase
 * twin, and the camelCase of each shorter suffix of at least two segments -
 * the port often drops the module prefix (borg_defend_aux_bless is
 * defend.ts's auxBless).
 */
function namesFor(name) {
  const parts = name.split("_");
  const forms = [name, camel(name)];
  for (let i = 1; parts.length - i >= 2; i++) forms.push(camel(parts.slice(i).join("_")));
  return [...new Set(forms)];
}

function whereNamed(name) {
  const patterns = namesFor(name).map((form) => new RegExp(`\\b${form}\\b`, "u"));
  return port.filter((f) => patterns.some((re) => re.test(f.text))).map((f) => f.path);
}

const files = readdirSync(C_DIR).filter((f) => f.endsWith(".c")).sort();
const report = [];
let total = 0;
let covered = 0;
for (const file of files) {
  const defs = definitions(file);
  const rows = defs.map((d) => ({ ...d, where: whereNamed(d.name) }));
  total += rows.length;
  covered += rows.filter((r) => r.where.length > 0).length;
  report.push({ file, rows });
}

console.log(`C functions: ${String(total)}; named in the port: ${String(covered)}; not named: ${String(total - covered)}`);
for (const { file, rows } of report) {
  const missing = rows.filter((r) => r.where.length === 0);
  if (missing.length > 0) console.log(`  ${file.padEnd(26)} ${String(missing.length).padStart(3)} of ${String(rows.length).padStart(3)} not named: ${missing.map((r) => r.name).join(", ")}`);
}

if (process.argv.includes("--write")) {
  const md = [
    "# C-function coverage map (#34)",
    "",
    "Generated by `node tools/c-coverage.mjs --write`; do not edit by hand.",
    "Every `borg_*` function the 4.2.6 C borg defines (`../neo-angband/reference/src/borg/`), and whether the port names it - by its C name or its camelCase twin.",
    "**Not named** is a candidate gap to classify, not a verdict; **named** is not yet proven faithful.",
    "",
    `**${String(covered)} of ${String(total)}** named; **${String(total - covered)}** not named.`,
    "",
  ];
  for (const { file, rows } of report) {
    const missing = rows.filter((r) => r.where.length === 0);
    md.push(`## ${file} - ${String(rows.length - missing.length)}/${String(rows.length)} named`, "");
    if (missing.length > 0) {
      md.push("| Not named | C line |", "| --- | --- |");
      for (const r of missing) md.push(`| \`${r.name}\` | ${file}:${String(r.line)} |`);
      md.push("");
    }
  }
  writeFileSync(join(ROOT, "docs", "audit", "c-coverage.md"), md.join("\n") + "\n");
  console.log("wrote docs/audit/c-coverage.md");
}
