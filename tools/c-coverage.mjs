#!/usr/bin/env node
/**
 * The C-function coverage map (#34): every `borg_*` function the 4.2.6 C
 * borg defines, and whether the port names it anywhere - by its C name
 * (the port cites C names in comments, e.g. "borg_flow_recover
 * (borg-flow-misc.c)"), by its camelCase twin (`borgFlowRecover`), or by
 * a shorter camelCase suffix (`auxBless` for borg_defend_aux_bless).
 *
 *   node tools/c-coverage.mjs                 summary on stdout
 *   node tools/c-coverage.mjs --write         also write docs/audit/c-coverage.md
 *   node tools/c-coverage.mjs --write-classification  render B61's reviewed data
 *   node tools/c-coverage.mjs --check-classification  verify all original 145
 *
 * An uncovered function is a CANDIDATE gap, not a verdict: it may be
 * C-only plumbing (keypress queues, screen scraping, the cheat pipe) with
 * nothing to port, or merged into another function under a different name.
 * Each uncovered one is classified by reading it (docs/audit/), the way the
 * declared-gaps inventory classifies the port's own markers. A covered one
 * is named, not proven faithful: the subsystem audit checks those.
 *
 * Reads the C from ../neo-angband/reference/src/borg/ and the port's src/
 * (tests excluded).
 */

import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(fileURLToPath(new URL("./", import.meta.url)), "..");
const C_DIR = resolve(ROOT, "..", "neo-angband", "reference", "src", "borg");
const SRC = join(ROOT, "src");

/** Every borg_* function DEFINED in a C file: a line starting with a type that names it before "(". */
function definitions(file) {
  const out = [];
  const lines = readFileSync(join(C_DIR, file), "utf8").split("\n");
  lines.forEach((line, i) => {
    const m = /^[a-z][^=;(]*?[\s*](borg_[a-z0-9_]+)\(/u.exec(line);
    if (m === null || /^\s/u.test(line)) return;
    /* A prototype ends in ");" on its own line; a definition does not. */
    if (/\)\s*;\s*$/u.test(line)) return;
    out.push({ name: m[1], line: i + 1 });
  });
  return out;
}

function camel(name) {
  return name.replace(/_([a-z0-9])/gu, (_, c) => c.toUpperCase());
}

function walk(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((d) =>
    d.isDirectory() ? walk(join(dir, d.name)) : d.name.endsWith(".ts") && !d.name.endsWith(".test.ts") ? [join(dir, d.name)] : [],
  );
}

const port = walk(SRC).map((path) => ({ path: path.slice(ROOT.length + 1), text: readFileSync(path, "utf8") }));

/**
 * The names the port may use for a C function: the C name, its camelCase
 * twin, and the camelCase of each shorter suffix of at least two segments -
 * the port often drops the module prefix (borg_defend_aux_bless is
 * defend.ts's auxBless).
 */
function namesFor(name) {
  const parts = name.split("_");
  const forms = [name, camel(name)];
  for (let i = 1; parts.length - i >= 2; i++) forms.push(camel(parts.slice(i).join("_")));
  return [...new Set(forms)];
}

function whereNamed(name) {
  const patterns = namesFor(name).map((form) => new RegExp(`\\b${form}\\b`, "u"));
  return port.filter((f) => patterns.some((re) => re.test(f.text))).map((f) => f.path);
}

const files = readdirSync(C_DIR).filter((f) => f.endsWith(".c")).sort();
const report = [];
let total = 0;
let covered = 0;
for (const file of files) {
  const defs = definitions(file);
  const rows = defs.map((d) => ({ ...d, where: whereNamed(d.name) }));
  total += rows.length;
  covered += rows.filter((r) => r.where.length > 0).length;
  report.push({ file, rows });
}

console.log(`C functions: ${String(total)}; named in the port: ${String(covered)}; not named: ${String(total - covered)}`);
for (const { file, rows } of report) {
  const missing = rows.filter((r) => r.where.length === 0);
  if (missing.length > 0) console.log(`  ${file.padEnd(26)} ${String(missing.length).padStart(3)} of ${String(rows.length).padStart(3)} not named: ${missing.map((r) => r.name).join(", ")}`);
}

if (process.argv.includes("--write")) {
  const md = [
    "# C-function coverage map (#34)",
    "",
    "Generated by `node tools/c-coverage.mjs --write`; do not edit by hand.",
    "Every `borg_*` function the 4.2.6 C borg defines (`../neo-angband/reference/src/borg/`), and whether the port names it - by its C name or its camelCase twin.",
    "**Not named** is a candidate gap to classify, not a verdict; **named** is not yet proven faithful.",
    "",
    `**${String(covered)} of ${String(total)}** named; **${String(total - covered)}** not named.`,
    "",
  ];
  for (const { file, rows } of report) {
    const missing = rows.filter((r) => r.where.length === 0);
    md.push(`## ${file} - ${String(rows.length - missing.length)}/${String(rows.length)} named`, "");
    if (missing.length > 0) {
      md.push("| Not named | C line |", "| --- | --- |");
      for (const r of missing) md.push(`| \`${r.name}\` | ${file}:${String(r.line)} |`);
      md.push("");
    }
  }
  writeFileSync(join(ROOT, "docs", "audit", "c-coverage.md"), md.join("\n") + "\n");
  console.log("wrote docs/audit/c-coverage.md");
}

/* B61's reviewed classification is separate from the name matcher. A suffix
 * in a hook or comment does not prove that its C body was ported. */
if (process.argv.includes("--write-classification") || process.argv.includes("--check-classification")) {
  const dataPath = join(ROOT, "docs", "audit", "c-classification.json");
  const mdPath = join(ROOT, "docs", "audit", "c-classification.md");
  const data = JSON.parse(readFileSync(dataPath, "utf8"));
  const fail = (message) => { throw new Error(`classification: ${message}`); };
  const categories = ["plumbing", "merged", "legitimate", "gap"];
  if (data.schema !== "mandos/c-classification@1" || !Array.isArray(data.rows)) fail("unknown schema");
  if (data.baseline?.count !== 145 || data.rows.length !== 145) fail("must classify all 145 original entries");
  const definitionsByName = new Map(report.flatMap(({ file, rows }) => rows.map((row) => [row.name, { ...row, file }])));
  const byName = new Map();
  const counts = Object.fromEntries(categories.map((category) => [category, 0]));
  for (const row of data.rows) {
    if (byName.has(row.name)) fail(`duplicate ${String(row.name)}`);
    const source = definitionsByName.get(row.name);
    if (!source || source.file !== row.file || source.line !== row.line) fail(`wrong C reference for ${String(row.name)}`);
    if (!categories.includes(row.category)) fail(`unknown category for ${row.name}`);
    if (typeof row.evidence !== "string" || row.evidence.trim() === "") fail(`missing evidence for ${row.name}`);
    if (!Array.isArray(row.port) || row.port.length === 0) fail(`missing implementation/boundary reference for ${row.name}`);
    for (const path of row.port) {
      if (typeof path !== "string" || path.startsWith("/") || path.split("/").includes("..") || !existsSync(join(ROOT, path))) {
        fail(`invalid local reference ${String(path)} for ${row.name}`);
      }
    }
    if (!Array.isArray(row.issues) || row.issues.some((issue) => !Number.isInteger(issue) || issue <= 0)) fail(`invalid issue list for ${row.name}`);
    if (row.category === "gap" && row.issues.length === 0) fail(`untracked gap ${row.name}`);
    byName.set(row.name, row);
    counts[row.category]++;
  }
  const namesHash = createHash("sha256").update([...byName.keys()].sort().join("\n")).digest("hex");
  if (namesHash !== data.baseline.namesSha256) fail("original name set changed");
  const missingNow = [...definitionsByName.values()].filter((row) => row.where.length === 0);
  for (const row of missingNow) if (!byName.has(row.name)) fail(`new unclassified candidate ${row.name}`);
  const namedSince = data.rows.filter((row) => definitionsByName.get(row.name).where.length > 0);
  const md = [
    "# C-function classification (#61)", "",
    "Generated by `node tools/c-coverage.mjs --write-classification` from the reviewed `c-classification.json`.", "",
    "This classifies the **original 145** entries from the 318/463 name census. It is not a whole-port fidelity certificate: a mapped entry point can still have defects, and a name match in a comment or hook does not prove an implementation.", "",
    `Current name census: **${String(covered)}/${String(total)} named**, **${String(total - covered)} unnamed**. All current unnamed candidates are accounted for below; ${String(namedSince.length)} original entries now match a name.`, "",
    "| Classification | Functions | Meaning |", "| --- | ---: | --- |",
    `| plumbing | ${String(counts.plumbing)} | C memory, terminal or diagnostic representation with no separate tactical routine to port. |`,
    `| merged | ${String(counts.merged)} | Concrete replacement entry points in the port or host; full subsystem fidelity remains a separate audit. |`,
    `| legitimate | ${String(counts.legitimate)} | A declared-data/UI boundary or an explicitly unsupported optional C mode. Limitations are named, rather than called implemented. |`,
    `| gap | ${String(counts.gap)} | Missing decision/adapter logic, linked to a tracked issue. |`, "",
    "The optional dynamic-formula, lunal and full munchkin modes are outside the supported stock policy. Their rows do not claim parity if those modes are enabled. A missing producer in our model is not automatically an engine-data limitation.", "",
    "## Gaps to address", "",
    `The ${String(counts.gap)} gap functions group under [swaps #4](https://github.com/diegoami/mandos/issues/4), [genocide-family defenses #75](https://github.com/diegoami/mandos/issues/75), [home combination search #79](https://github.com/diegoami/mandos/issues/79), [Morgoth defenses #80](https://github.com/diegoami/mandos/issues/80) and [item analysis #81](https://github.com/diegoami/mandos/issues/81). These are defect investigations, not newly implemented features or measured strength claims.`, "",
    "## Reconcile the name counts", "",
    "- `borg_can_play_spell`: restored by B63 as `borgCanPlaySpell`.",
    "- `borg_consume`: restored by B50 as `borgConsume`.",
    "- `borg_ego_has_random_power`: the new `randomPower` hook triggers the broad suffix matcher, but the actual metadata predicate is still a gap (#81).",
    "- Other names outside this original list can also be false positives: for example, `valueKnown` means \"a value field exists\", not the C `borg_object_value_known` implementation. The item-analysis issue records that distinction.", "",
    "## Reviewed entries", "",
  ];
  const escape = (text) => text.replaceAll("|", "\\|").replaceAll("\n", " ");
  for (const { file } of report) {
    const rows = data.rows.filter((row) => row.file === file);
    if (rows.length === 0) continue;
    md.push(`### ${file}`, "", "| C function / line | Class | Evidence and replacement/boundary | Tracker |", "| --- | --- | --- | --- |");
    for (const row of rows) {
      const paths = row.port.map((path) => `[${path}](../../${path})`).join(", ");
      const issues = row.issues.map((issue) => `[#${String(issue)}](https://github.com/diegoami/mandos/issues/${String(issue)})`).join(", ") || "—";
      md.push(`| \`${row.name}\` (${String(row.line)}) | ${row.category} | ${escape(row.evidence)} ${paths} | ${issues} |`);
    }
    md.push("");
  }
  const rendered = `${md.join("\n")}\n`;
  if (process.argv.includes("--write-classification")) writeFileSync(mdPath, rendered);
  if (process.argv.includes("--check-classification") && (!existsSync(mdPath) || readFileSync(mdPath, "utf8") !== rendered)) {
    fail("generated Markdown is stale; run --write-classification");
  }
  console.log(`Classification checked: 145/145; plumbing ${String(counts.plumbing)}, merged ${String(counts.merged)}, legitimate ${String(counts.legitimate)}, gap ${String(counts.gap)}; ${String(missingNow.length)} current unnamed entries covered.`);
}
